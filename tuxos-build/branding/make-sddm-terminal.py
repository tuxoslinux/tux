#!/usr/bin/env python3
"""Writes the "Terminal" SDDM theme's Main.qml with the ASCII Tux embedded.

    make_terminal.py tux-ascii.txt Main.qml
"""
import html
import json
import re
import sys

WHITE, YELLOW = '#cdcdcd', '#d6c828'

lines = open(sys.argv[1]).read().rstrip('\n').split('\n')
out = []
for line in lines:
    parts, color = [], WHITE
    for part in re.split(r'(\$[12])', line):
        if part == '$1':
            color = WHITE
        elif part == '$2':
            color = YELLOW
        elif part:
            parts.append(f'<span style="color:{color}">{html.escape(part)}</span>')
    out.append(''.join(parts))
art_html = '<pre>' + '\n'.join(out) + '</pre>'

qml = r'''/***************************************************************************
* TuxOS login screen "Terminal": a text-console style login next to the
* ASCII Tux (the same art as fastfetch). Generated by make_terminal.py.
***************************************************************************/

import QtQuick 2.0
import SddmComponents 2.0

Rectangle {
    id: container
    width: 1280
    height: 800
    color: "#000000"

    property int sessionIndex: session.index

    readonly property color accent: "#f5b800"
    readonly property color textColor: "#cdcdcd"
    readonly property color mutedColor: "#6f6f6f"
    readonly property string mono: "Noto Sans Mono"
    readonly property int fontSize: Math.max(15, Math.round(height / 48))

    TextConstants { id: textConstants }

    function doLogin() {
        statusText.color = container.mutedColor
        statusText.text = "Logging in..."
        sddm.login(name.text, password.text, sessionIndex)
    }

    Connections {
        target: sddm

        function onLoginSucceeded() {
            statusText.color = container.mutedColor
            statusText.text = textConstants.loginSucceeded
        }

        function onLoginFailed() {
            password.text = ""
            password.focus = true
            statusText.color = "#ff6b6b"
            statusText.text = "Login incorrect"
        }

        function onInformationMessage(message) {
            statusText.color = "#ff6b6b"
            statusText.text = message
        }
    }

    Text {
        id: art
        anchors { left: parent.left; leftMargin: parent.width * 0.07; verticalCenter: parent.verticalCenter }
        textFormat: Text.RichText
        font.family: container.mono
        font.pixelSize: Math.round(container.fontSize * 0.82)
        text: ART_HTML
    }

    Column {
        id: consoleColumn
        anchors { left: art.right; leftMargin: parent.width * 0.06; verticalCenter: parent.verticalCenter }
        spacing: Math.round(container.fontSize * 0.7)

        Text {
            font.family: container.mono
            font.pixelSize: container.fontSize
            color: container.textColor
            text: "TuxOS " + sddm.hostName + " (graphical login)"
        }

        Text {
            font.family: container.mono
            font.pixelSize: container.fontSize
            color: container.mutedColor
            text: Qt.formatDateTime(new Date(), "ddd d MMM yyyy  hh:mm")
            Timer {
                interval: 10000; running: true; repeat: true
                onTriggered: parent.text = Qt.formatDateTime(new Date(), "ddd d MMM yyyy  hh:mm")
            }
        }

        Item { width: 1; height: container.fontSize }

        Row {
            spacing: 0
            Text {
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.accent
                text: sddm.hostName + " login: "
            }
            TextInput {
                id: name
                width: container.fontSize * 18
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.textColor
                text: userModel.lastUser
                cursorVisible: activeFocus
                selectionColor: container.accent
                KeyNavigation.tab: password; KeyNavigation.backtab: rebootText
                Keys.onReturnPressed: password.focus = true
                Keys.onEnterPressed: password.focus = true
            }
        }

        Row {
            spacing: 0
            Text {
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.accent
                text: "Password: "
            }
            TextInput {
                id: password
                width: container.fontSize * 18
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.textColor
                echoMode: TextInput.Password
                passwordCharacter: "*"
                cursorVisible: activeFocus
                selectionColor: container.accent
                KeyNavigation.tab: session; KeyNavigation.backtab: name
                Keys.onReturnPressed: container.doLogin()
                Keys.onEnterPressed: container.doLogin()
            }
        }

        Row {
            spacing: 0
            z: 100
            Text {
                anchors.verticalCenter: parent.verticalCenter
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.accent
                text: "Session:  "
            }
            ComboBox {
                id: session
                width: container.fontSize * 16; height: container.fontSize * 1.8
                font.family: container.mono
                font.pixelSize: container.fontSize - 2
                color: "#000000"
                borderColor: "#333333"
                focusColor: container.accent
                hoverColor: container.accent
                textColor: container.textColor
                menuColor: "#0d0d0d"
                arrowColor: "#000000"
                arrowIcon: Qt.resolvedUrl("angle-down.png")
                model: sessionModel
                index: sessionModel.lastIndex
                KeyNavigation.backtab: password; KeyNavigation.tab: layoutBox
            }
            Text {
                anchors.verticalCenter: parent.verticalCenter
                font.family: container.mono
                font.pixelSize: container.fontSize
                color: container.accent
                text: "  Keys: "
            }
            LayoutBox {
                id: layoutBox
                width: container.fontSize * 5; height: container.fontSize * 1.8
                font.family: container.mono
                font.pixelSize: container.fontSize - 2
                color: "#000000"
                borderColor: "#333333"
                focusColor: container.accent
                hoverColor: container.accent
                textColor: container.textColor
                menuColor: "#0d0d0d"
                arrowColor: "#000000"
                arrowIcon: Qt.resolvedUrl("angle-down.png")
                KeyNavigation.backtab: session; KeyNavigation.tab: shutdownText
            }
        }

        Text {
            id: statusText
            font.family: container.mono
            font.pixelSize: container.fontSize - 2
            color: container.mutedColor
            text: keyboard.capsLock ? textConstants.capslockWarning : "Type your password and press Enter"
        }

        Item { width: 1; height: container.fontSize }

        Row {
            spacing: container.fontSize * 2
            Text {
                id: shutdownText
                font.family: container.mono
                font.pixelSize: container.fontSize - 2
                color: activeFocus || shutdownArea.containsMouse ? container.accent : container.mutedColor
                text: "[ " + textConstants.shutdown + " ]"
                KeyNavigation.backtab: layoutBox; KeyNavigation.tab: rebootText
                Keys.onReturnPressed: sddm.powerOff()
                Keys.onSpacePressed: sddm.powerOff()
                MouseArea {
                    id: shutdownArea
                    anchors.fill: parent
                    hoverEnabled: true
                    cursorShape: Qt.PointingHandCursor
                    onClicked: sddm.powerOff()
                }
            }
            Text {
                id: rebootText
                font.family: container.mono
                font.pixelSize: container.fontSize - 2
                color: activeFocus || rebootArea.containsMouse ? container.accent : container.mutedColor
                text: "[ " + textConstants.reboot + " ]"
                KeyNavigation.backtab: shutdownText; KeyNavigation.tab: name
                Keys.onReturnPressed: sddm.reboot()
                Keys.onSpacePressed: sddm.reboot()
                MouseArea {
                    id: rebootArea
                    anchors.fill: parent
                    hoverEnabled: true
                    cursorShape: Qt.PointingHandCursor
                    onClicked: sddm.reboot()
                }
            }
        }
    }

    Component.onCompleted: {
        if (name.text == "")
            name.focus = true
        else
            password.focus = true
    }
}
'''
open(sys.argv[2], 'w').write(qml.replace('ART_HTML', json.dumps(art_html)))
